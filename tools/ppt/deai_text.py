def all_shapes(shapes):
    for sh in shapes:
        yield sh
        if sh.shape_type == 6:
            yield from all_shapes(sh.shapes)


def replace_in_shape(shape, mapping):
    count = 0
    for para in shape.text_frame.paragraphs:
        old = ''.join(run.text for run in para.runs)
        if old in mapping:
            new = mapping[old]
            runs = para.runs
            if runs:
                runs[0].text = new
                for run in runs[1:]:
                    run.text = ''
            count += 1
    return count


def main():
    if not BACKUP.exists():
        BACKUP.write_bytes(PPT.read_bytes())
        print('backup ->', BACKUP)
    prs = Presentation(str(PPT))
    total = 0
    missed = []
    for slide_no, changes in CHANGES.items():
        slide = prs.slides[slide_no - 1]
        shapes = list(all_shapes(slide.shapes))
        for name, mapping in changes.items():
            candidates = [s for s in shapes if s.name == name and getattr(s, 'has_text_frame', False)]
            if not candidates:
                missed.append(f'slide {slide_no} shape {name} not found')
                continue
            for shape in candidates:
                done = replace_in_shape(shape, mapping)
                total += done
                if done == 0:
                    # 名字重复时可能一段分散在多个同形状里：未命中不报错，最后统一核对
                    pass
    prs.save(str(PPT))
    print('replaced', total, 'paragraphs')
    if missed:
        print('MISSED:', missed)


if __name__ == '__main__':
    main()
