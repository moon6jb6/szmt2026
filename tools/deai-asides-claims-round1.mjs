let changed = 0

for (const [file, notes] of Object.entries(ASIDES)) {
  let s = await readFile(file, 'utf8')
  let index = 0
  s = s.replace(/(aside:\s*)(['"])((?:[^'"\\]|\\.)*)\2/g, (m, prefix, quote, old) => {
    if (index >= notes.length) return m
    const next = notes[index]
    index += 1
    changed += 1
    return `${prefix}${quote}${next.replace(/\\/g, '\\\\').replace(new RegExp(quote, 'g'), `\\${quote}`)}${quote}`
  })
  if (index !== notes.length) console.log(`WARN ${file}: replaced ${index}/${notes.length}`)
  await writeFile(file, s, 'utf8')
}

let auto = await readFile('src/game/content/sources.auto.ts', 'utf8')
for (const [id, claim] of Object.entries(CLAIMS)) {
  const re = new RegExp(`("id":\\s*"${id}"[\\s\\S]*?"claim":\\s*)"(?:[^"\\\\]|\\\\.)*"`)
  if (re.test(auto)) {
    auto = auto.replace(re, `$1${JSON.stringify(claim)}`)
    changed += 1
  } else {
    console.log('MISS claim', id)
  }
}
await writeFile('src/game/content/sources.auto.ts', auto, 'utf8')

// 研究 JSON：从改完的 auto 提取 note，写回 filled[]
const reNote = /"id":\s*"([^"]+)"[\s\S]*?"note":\s*"((?:[^"\\]|\\.)*)"/g
const notes = {}
let m
while ((m = reNote.exec(auto))) notes[m[1]] = JSON.parse(`"${m[2]}"`)
try {
  const jp = 'docs/deliverables/史料收集回填.json'
  const data = JSON.parse(await readFile(jp, 'utf8'))
  let hit = 0
  for (const item of data.filled ?? []) {
    if (item?.id && notes[item.id]) {
      item.note = notes[item.id]
      hit += 1
    }
  }
  await writeFile(jp, JSON.stringify(data, null, 2) + '\n', 'utf8')
  console.log('json notes synced:', hit)
} catch (error) {
  console.log('json skip:', error.message)
}

console.log('changed:', changed)
