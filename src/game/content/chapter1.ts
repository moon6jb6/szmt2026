export function buildEpilogue(ledger: Ledger): Scene {
  const kinds = (Object.keys(ledger) as (keyof Ledger)[]).filter((kind) => ledger[kind] > 0)
  const choices: Choice[] = kinds.map((kind) => ({
    id: `epi-${kind}`,
    label: MEMORY_LABELS[kind].label,
    hint: MEMORY_LABELS[kind].hint,
    outcome: {
      paragraphs: COMMIT_TEXT[kind],
    },
    next: ENDING_SCENE[kind],
    ending: kind,
  }))

  // 合成结局：两个载体同时在场时出现，表现"记忆互相作证"
  for (const kind of COMPOSITE_ORDER) {
    const [a, b] = COMPOSITE_REQUIRES[kind]
    if (ledger[a] > 0 && ledger[b] > 0) {
      const meta = COMPOSITE_LABELS[kind]
      choices.push({
        id: `epi-${kind}`,
        label: meta.label,
        hint: meta.hint,
        outcome: { paragraphs: COMMIT_COMPOSITE[kind] },
        next: `ending_${kind}`,
        ending: kind,
      })
    }
  }

  // 兜底：什么都没留下时，至少允许交那句话
  if (choices.length === 0) {
    choices.push({
      id: 'epi-message',
      label: MEMORY_LABELS.message.label,
      hint: MEMORY_LABELS.message.hint,
      outcome: { paragraphs: COMMIT_TEXT.message },
      next: ENDING_SCENE.message,
      ending: 'message',
    })
  }

  return { ...EPILOGUE_BASE, choices }
}

